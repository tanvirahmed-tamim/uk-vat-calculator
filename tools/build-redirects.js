// Regenerates _redirects from the pages on disk.
//
// Every page keeps a 301 from its legacy .html path to the extensionless URL,
// so Search Console sees a direct 301 instead of Cloudflare Pages' automatic
// 302. Run this after adding or renaming any page.
//
//   node tools/build-redirects.js

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SKIP = new Set([".git", "node_modules", "assets", "tools", ".github"]);
const ALIASES = [
  ["/guides/vat-rates-explained", "/guides/vat-rates"],
  ["/guides/vat-for-overseas-clients", "/guides/vat-for-professional-services"],
];

function pages(dir, prefix = "") {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP.has(entry.name)) continue;
      out.push(...pages(path.join(dir, entry.name), `${prefix}${entry.name}/`));
    } else if (entry.name.endsWith(".html")) {
      out.push(`${prefix}${entry.name}`);
    }
  }
  return out;
}

const files = pages(ROOT)
  .filter((rel) => rel !== "404.html")
  .sort();

const lines = [
  "# Generated by tools/build-redirects.js. Run it after adding any page.",
  "",
  "# Legacy guide aliases, in both forms so the extensionless variant cannot 404",
];

for (const [from, to] of ALIASES) {
  lines.push(`${from} ${to} 301`);
  lines.push(`${from}.html ${to} 301`);
}

lines.push("", "# .html path to extensionless URL, one rule per page");

for (const rel of files) {
  const target = rel === "index.html" ? "/" : "/" + rel.replace(/\.html$/, "");
  lines.push(`/${rel} ${target} 301`);
}

fs.writeFileSync(path.join(ROOT, "_redirects"), lines.join("\n") + "\n");
console.log(`wrote _redirects with ${files.length} page rules and ${ALIASES.length * 2} alias rules`);
